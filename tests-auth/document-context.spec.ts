import { test, expect } from "@playwright/test";
test("Mother creates a printable summary and reviews real PDF text for private MatriSathi read-back", async ({ page, context }, info) => {
  test.setTimeout(90000);
  const fixture = await context.newPage();
  await fixture.setContent("<h1>Fictional visit record</h1><p>Follow-up date: 2026-11-08.</p><p>Recorded by Synthetic Clinic.</p>");
  const original = await fixture.pdf({ format: "A4" }); await fixture.close();
  await page.goto("/auth/signup?role=mother");
  await page.getByLabel("Email address", { exact: true }).fill(`document-context-${Date.now()}@example.test`);
  await page.getByLabel("Password", { exact: true }).fill("Synthetic-test-42!");
  await page.getByLabel("Confirm password", { exact: true }).fill("Synthetic-test-42!");
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.locator(".demo-banner")).toContainText("Signed-in account");
  await page.goto("/mother/more/profile");
  await page.getByLabel("Full name", { exact: true }).fill("Mira Submission Example");
  await page.getByLabel("Recorded pregnancy week (optional)").fill("22");
  await page.getByLabel("Pregnancy week recorded on").fill("2026-11-07");
  await page.getByRole("button", { name: "Save mother profile" }).click();
  await expect(page.getByRole("status")).toContainText("saved encrypted");
  await page.goto("/mother/health/reports");
  await page.getByRole("button", { name: "Upload From Device" }).click();
  await page.getByLabel("Document", { exact: true }).setInputFiles({ name: "fictional-visit.pdf", mimeType: "application/pdf", buffer: original });
  await page.getByLabel("Issuing facility / source (optional)").fill("Synthetic Clinic");
  await page.getByLabel("Document date (optional)").fill("2026-11-07");
  await page.getByRole("button", { name: "Save document", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Saved encrypted");
  await page.goto("/mother/overview");
  await page.getByRole("button", { name: "Create care summary", exact: true }).click();
  const frame = page.frameLocator('iframe[title="Personal care summary preview"]');
  await expect(frame.getByRole("heading", { name: "Mira Submission Example" })).toBeVisible();
  await expect(frame.locator("body")).toContainText("fictional-visit.pdf");
  const html = await page.locator('iframe[title="Personal care summary preview"]').getAttribute("srcdoc");
  const print = await context.newPage(); await print.setContent(html!);
  await print.pdf({ path: info.outputPath("personal-care-summary.pdf"), format: "A4", preferCSSPageSize: true }); await print.close();
  await page.goto("/mother/matrisathi/companion/settings");
  const external: string[] = []; page.on("request", r => { if (!new URL(r.url()).hostname.includes("127.0.0.1")) external.push(r.url()); });
  await page.getByRole("button", { name: "Choose from my uploaded documents" }).click();
  await page.getByLabel("Document for this chat").selectOption({ label: "fictional-visit.pdf" });
  await page.getByRole("button", { name: "Extract PDF text on this device" }).click();
  await expect(page.getByLabel("Text reviewed against the original")).toHaveValue(/Follow-up date: 2026-11-08/);
  await expect(page.getByRole("button", { name: "Use reviewed text in this chat" })).toBeDisabled();
  await page.getByRole("checkbox", { name: /I checked this text/ }).check();
  await page.getByRole("button", { name: "Use reviewed text in this chat" }).click();
  await page.getByRole("link", { name: "Back to Chat", exact: true }).click();
  await context.setOffline(true);
  await page.getByRole("button", { name: "Read my document", exact: true }).click();
  await page.getByRole("button", { name: "Send", exact: true }).click();
  await expect(page.getByRole("log")).toContainText("Follow-up date: 2026-11-08");
  await expect(page.getByRole("log")).toContainText("Exact read-back · Not AI-generated");
  await page.getByLabel("Your message", { exact: true }).fill("What does my report mean?");
  await page.getByRole("button", { name: "Send", exact: true }).click();
  await expect(page.getByRole("log")).toContainText("can't interpret");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: info.outputPath("ruhi-document-mobile.png"), fullPage: true });
  await page.getByRole("button", { name: "New chat", exact: true }).click();
  await page.getByRole("button", { name: "Read my document", exact: true }).click();
  await page.getByRole("button", { name: "Send", exact: true }).click();
  await expect(page.getByRole("log")).toContainText("have not read any other file");
  await expect(page.getByRole("log")).not.toContainText("2026-11-08");
  expect(external).toEqual([]);
});
